"""starter.py - employers a fresh install can read on day one.

Twelve of the fifteen collectors are per-employer: they sit idle until
somebody names companies, and nobody can invent forty employer names cold.
That is the real onboarding barrier - not the config, not the resume, not
the search terms. Three sources need no list at all - USAJOBS, Remote OK
and NoDesk - and between them they are still a thin slice of the market.

WHAT IS IN HERE, AND WHAT IS DELIBERATELY NOT
Nationally-operating employers only. No regional names: a shipped pack
carrying one metro's employers is dead weight to everyone outside it and
reads as an oversight to everyone in it (decided 2026-08-04).

Chosen for BREADTH OF FUNCTION, not industry. Internal roles - IT, HR,
maintenance, accounting, facilities, security - exist at every employer, so
a wide employer base matters more than an industry-curated list. The sector
tag on each entry is there so somebody can delete what they do not want,
not so the list can be filtered into a specialism.

A FLAT LIST, added whole, rather than opt-in bundles. Bundles would put the
industry-curation mistake back in by the front door: a warehouse manager
who picks "logistics" never sees that the hospital down the road needs a
facilities supervisor.

EVERY ENTRY WAS MEASURED, NOT ASSUMED. Each name here was resolved to a
board and then collected from, and only names that returned live postings
survived. A name that cannot be read is worse than no name, because it teaches
somebody on their first afternoon that the tool does not work.

THE REFERENCES REPAIR THEMSELVES. Employers change ATS without announcing
it, and a stored reference that stops returning postings would otherwise leave
that employer silent for ever - indistinguishable, on screen, from one that is
simply not hiring. `collect` counts the consecutive collections on which a
board returns nothing, and after three it re-probes that ONE employer and
writes the new reference. See rediscover.heal_one for why that is not the
scheduled crawl this app refuses to be, and why a probe that finds nothing is
never allowed to blank a board.

So the pack is still a starting point somebody edits - the sector tags exist
to be deleted from - but it is no longer a list that quietly stops working.
"""
