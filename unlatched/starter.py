def by_sector() -> dict[str, list[Employer]]:
    """The pack grouped for display. Insertion order per sector is the order
    they are listed above, which is alphabetical within each group.
    """
    out: dict[str, list[Employer]] = {}
    for employer in EMPLOYERS:
        out.setdefault(employer.sector, []).append(employer)
    return out


def seed(con: sqlite3.Connection) -> tuple[int, int]:
    """Adds the pack to this profile. Returns (added, already_there).

    Never overwrites an employer the person already has, even when the pack
    knows a different board for it: their entry may be a correction, and a
    seed that quietly reverts a correction is worse than one that skips.
    """
    added = skipped = 0
    for employer in EMPLOYERS:
        if db.get_company(con, employer.name) is not None:
            skipped += 1
            continue
        db.upsert_company(con, employer.name, careers_url=employer.careers_url,
                          ats=employer.ats, ats_ref=employer.ats_ref,
                          probe_status="yielding", origin=db.SEEDED)
        added += 1
    return added, skipped


def as_dicts() -> list[dict[str, Any]]:
    """For `--json` output and for anything that wants the pack without
    importing the NamedTuple.
    """
    return [e._asdict() for e in EMPLOYERS]
